// i18n & Theme management for CS Daily System

export type Language = 'km' | 'en' | 'zh';
export type Theme = 'dark' | 'light';

export const STORAGE_KEY_LANG = 'cs_app_language';
export const STORAGE_KEY_THEME = 'cs_app_theme';

export const getStoredLanguage = (): Language => {
  const stored = localStorage.getItem(STORAGE_KEY_LANG);
  if (stored === 'en' || stored === 'zh' || stored === 'km') return stored;
  return 'km'; // default Khmer
};

export const setStoredLanguage = (lang: Language) => {
  localStorage.setItem(STORAGE_KEY_LANG, lang);
};

export const getStoredTheme = (): Theme => {
  const stored = localStorage.getItem(STORAGE_KEY_THEME);
  if (stored === 'light' || stored === 'dark') return stored;
  return 'dark'; // default dark
};

export const setStoredTheme = (theme: Theme) => {
  localStorage.setItem(STORAGE_KEY_THEME, theme);
};

